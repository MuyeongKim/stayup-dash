import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const workerPath = path.join(root, 'service-worker.js');
// Deliberately fixed: adding a renderer dependency requires a reviewed entry.
const paths = [
  'stayup-dash.html',
  'offline-map-engine.js',
  'vendor/maplibre-gl-5.24.0.js',
  'vendor/maplibre-gl-5.24.0.css',
  'vendor/pmtiles-4.5.0.js'
];
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const worker = readFileSync(workerPath, 'utf8');
const block = /\/\* OFFLINE_SHELL_MANIFEST_BEGIN \*\/[\s\S]*?\/\* OFFLINE_SHELL_MANIFEST_END \*\//;
if (!block.test(worker)) throw new Error('Service worker manifest markers are missing.');
const template = worker.replace(block, '/* OFFLINE_SHELL_MANIFEST */');
const assets = paths.map(file => ({path: file, sha256: digest(readFileSync(path.join(root, file)))}));
// Worker logic participates in the build identity, while generated bytes do not.
const build = digest(JSON.stringify({assets,worker: digest(template)})).slice(0, 24);
const manifest = {schema: 1, build, assets};
const generated = worker.replace(block, '/* OFFLINE_SHELL_MANIFEST_BEGIN */\nconst SHELL_MANIFEST = ' + JSON.stringify(manifest) + ';\n/* OFFLINE_SHELL_MANIFEST_END */');
const manifestText = JSON.stringify(manifest, null, 2) + '\n';
const manifestPath = path.join(root, 'offline-shell.json');
if (process.argv.includes('--check')) {
  let existing = '';
  try { existing = readFileSync(manifestPath, 'utf8'); } catch (_) {}
  if (generated !== worker || manifestText !== existing) throw new Error('오프라인 앱 목록이 오래되었습니다. node scripts/build-offline-shell.mjs 를 실행하세요.');
  console.log('오프라인 앱 목록 확인: ' + build + ' (' + assets.length + '개 파일)');
} else {
  writeFileSync(workerPath, generated);
  writeFileSync(manifestPath, manifestText);
  console.log('오프라인 앱 목록 생성: ' + build + ' (' + assets.length + '개 파일)');
}
